import { test,expect } from '@playwright/test';
test('imported dataset is used through backend across the complete workflow',async({page},testInfo)=>{
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('/portfolio');
  await page.getByLabel('Dataset',{exact:true}).selectOption('climateweb');
  await expect(page.getByLabel('Amount for Agilent Technologies')).toBeVisible();
  await page.getByLabel('Company search').fill('Agilent');
  await expect(page.getByLabel('Supported company').locator('option')).toHaveCount(1);
  await page.getByLabel('Choose CSV').setInputFiles({name:'source-holdings.csv',mimeType:'text/csv',buffer:Buffer.from('companyId,amount,currency,unit\na,10,INR,lakh\nabbv,40,INR,lakh\ncah,30,INR,lakh\ncvs,20,INR,lakh')});
  await page.getByRole('button',{name:'Commit reviewed import'}).click();
  await expect(page.getByText('Imported 4 holdings; 0 duplicate rows merged.')).toBeVisible();
  await page.goto('/locations');await page.getByLabel('Company selection').selectOption('a');
  await page.getByRole('button',{name:'Select facility',exact:true}).first().click();
  await page.getByRole('link',{name:'Inspect selection in graph'}).click();
  await expect(page.locator('main pre')).toContainText('demo-asset-a-01');
  await page.goto('/scenarios');
  const response=page.waitForResponse(r=>r.url().endsWith('/api/v1/analysis')&&r.request().method()==='POST');
  await page.getByRole('button',{name:'Run synthetic analysis'}).click();
  const run=await (await response).json();
  expect(run.sourceSnapshot.companies).toHaveLength(215);
  expect(run.sourceSnapshot.commercialEdges).toHaveLength(350);
  expect(run.scenarioSnapshot.datasetVersion).toContain('climateweb:');
  expect(run.totals.assumedWeightedExposure).toBeCloseTo(473532.89032269525,6);
  await expect(page.getByRole('heading',{name:'Analysis results',exact:true})).toBeVisible();
  const resultUrl=page.url();await page.screenshot({path:testInfo.outputPath('imported-results.png'),fullPage:true});
  await page.goto('/evidence');await expect(page.getByText('Sectivia supplied relationship dataset',{exact:true})).toBeVisible();
  await page.goto(resultUrl);await page.getByRole('link',{name:'Compare this snapshot'}).click();
  await page.getByLabel('From holding').selectOption('abbv');await page.getByLabel('To holding').selectOption('cvs');
  const compareResponse=page.waitForResponse(r=>r.url().endsWith('/api/v1/compare'));
  await page.getByRole('button',{name:'Compare transfer',exact:true}).click();
  const comparison=await (await compareResponse).json();expect(comparison.proposed.totals.assumedWeightedExposure).toBeCloseTo(431738.6903227998,6);
  expect(comparison.proposed.sourceSnapshot).toEqual(run.sourceSnapshot);
  await page.goto(resultUrl);await page.getByRole('button',{name:'Save report',exact:true}).click();
  await page.goto('/reports');await page.reload();await page.locator('main a').filter({hasText:/^20\d\d-/}).click();
  await expect(page).toHaveURL(resultUrl);
  const downloadPromise=page.waitForEvent('download');await page.getByRole('button',{name:'Export JSON'}).click();
  const download=await downloadPromise,stream=await download.createReadStream();let text='';for await(const chunk of stream)text+=chunk;
  const exported=JSON.parse(text);expect(exported.totals).toEqual(run.totals);expect(exported.sourceSnapshot.facilities[0].sourceFields.operational_share).toBeNull();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.getByLabel('Dataset',{exact:true}).selectOption('reference');await page.goto('/portfolio');
  await expect(page.getByLabel('Amount for Aster Motors')).toBeVisible();
  expect(errors).toEqual([]);
});
